def parse_pin(val):
    """智慧解析腳位輸入：支援整數、自由文字 ('13', 'A0'~'A15', 'D5', 'GPIO16' 等)"""
    if val is None:
        return 0
    s = str(val).strip().upper()
    if s.startswith("D") and len(s) > 1 and s[1:].isdigit():
        return int(s[1:])
    if s.startswith("A") and len(s) > 1 and s[1:].isdigit():
        return 14 + int(s[1:])
    if s.startswith("GPIO") and len(s) > 4 and s[4:].isdigit():
        return int(s[4:])
    try:
        return int(s)
    except ValueError:
        return 0

